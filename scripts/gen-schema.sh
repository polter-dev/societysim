#!/usr/bin/env bash
# Regenerate schema/events.schema.json (from the Pydantic models), viewer/src/types/events.ts
# (from that schema) and the static viewer-data schemas (index, leaderboard, metrics,
# highlights, narration_index; see docs/DATA_CONTRACT.md) and schema/game_setup.schema.json
# (the settings screen's GameSetup, societysim/setup.py) and schema/play_api.schema.json (the game
# server's Play API, societysim/server/app.py; needs the `server` extra). Check that they are current with:
#   ./scripts/gen-schema.sh && git diff --exit-code schema/ viewer/src/types/
set -euo pipefail
cd "$(dirname "$0")/.."

uv run --frozen --extra server python - <<'PY'
import json
from pathlib import Path

from pydantic.json_schema import GenerateJsonSchema

from societysim.logging.events import Event, Label


class NoFieldTitles(GenerateJsonSchema):
    # Field titles would each become a TS type alias; model titles are kept.
    def field_title_should_be_set(self, schema) -> bool:
        return False


schema = Event.model_json_schema(schema_generator=NoFieldTitles)
label = Label.model_json_schema(schema_generator=NoFieldTitles)
schema["$defs"].update(label.pop("$defs", {}))
schema["$defs"]["Label"] = label
# Every field of a closed model is always written (null when empty), so mark them all
# required and drop defaults. EventMeta is the exception: its None keys are not written.
# Fields marked "x-optional" (added in a later schema_version) stay optional so older logs
# still validate.
for s in (schema, *schema["$defs"].values()):
    if "properties" in s and s.get("additionalProperties") is not True:
        props = s["properties"]
        s["required"] = [k for k, v in props.items() if not v.pop("x-optional", False)]
        for k in s["required"]:
            props[k].pop("default", None)
schema = {"$schema": "https://json-schema.org/draft/2020-12/schema", **schema}
Path("schema/events.schema.json").write_text(json.dumps(schema, indent=2) + "\n")

# Static viewer data (docs/DATA_CONTRACT.md). Bump CONTRACT_VERSION on a breaking change
# (rename, removal, type change), per AGENTS.md hard rule 3.
from pydantic import TypeAdapter

from societysim.analysis.highlights import Highlights
from societysim.analysis.narrate import NarrationIndex
from societysim.analysis.report import GameIndex, Leaderboard, Metrics

CONTRACT_VERSION = 1


def tighten(node):
    # Every key is always written; the defaults only exist to make a few keys optional.
    # Keys that must match a pattern (seat ids, day numbers) allow nothing else.
    if isinstance(node, dict):
        node.pop("default", None)
        if "patternProperties" in node:
            node.setdefault("additionalProperties", False)
        for v in node.values():
            tighten(v)
    elif isinstance(node, list):
        for v in node:
            tighten(v)


for name, tp in [
    ("index", GameIndex),
    ("leaderboard", Leaderboard),
    ("metrics", Metrics),
    ("highlights", Highlights),
    ("narration_index", NarrationIndex),
]:
    s = TypeAdapter(tp).json_schema(by_alias=True, schema_generator=NoFieldTitles)
    tighten(s)
    s = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": f"{name}.schema.json",
        "x-contract-version": CONTRACT_VERSION,
        **s,
    }
    Path(f"schema/{name}.schema.json").write_text(json.dumps(s, indent=2) + "\n")

# What the settings screen submits; `play --setup` runs it.
from societysim.setup import setup_json_schema

Path("schema/game_setup.schema.json").write_text(json.dumps(setup_json_schema(), indent=2) + "\n")

# The game server's request and response bodies.
from societysim.server.app import play_api_json_schema

Path("schema/play_api.schema.json").write_text(json.dumps(play_api_json_schema(), indent=2) + "\n")
PY

mkdir -p viewer/src/types
npx --yes json-schema-to-typescript@15.0.4 \
  --input schema/events.schema.json \
  --output viewer/src/types/events.ts \
  --unreachableDefinitions \
  --bannerComment "/* Generated by scripts/gen-schema.sh from schema/events.schema.json. Do not edit. */"
