#!/usr/bin/env bash
# Regenerate schema/events.schema.json (from the Pydantic models) and
# viewer/src/types/events.ts (from that schema). Check that they are current with:
#   ./scripts/gen-schema.sh && git diff --exit-code schema/ viewer/src/types/
set -euo pipefail
cd "$(dirname "$0")/.."

uv run --frozen python - <<'PY'
import json
from pathlib import Path

from pydantic.json_schema import GenerateJsonSchema

from societysim.logging.events import Event, Label


class NoFieldTitles(GenerateJsonSchema):
    # Field titles would each become a TS type alias; model titles are kept.
    def field_title_should_be_set(self, schema) -> bool:
        return False


schema = Event.model_json_schema(schema_generator=NoFieldTitles)
label = Label.model_json_schema(schema_generator=NoFieldTitles)
schema["$defs"].update(label.pop("$defs", {}))
schema["$defs"]["Label"] = label
# Every field of a closed model is always written (null when empty), so mark them all
# required and drop defaults. EventMeta is the exception: its None keys are not written.
for s in (schema, *schema["$defs"].values()):
    if "properties" in s and s.get("additionalProperties") is not True:
        s["required"] = list(s["properties"])
        for prop in s["properties"].values():
            prop.pop("default", None)
schema = {"$schema": "https://json-schema.org/draft/2020-12/schema", **schema}
Path("schema/events.schema.json").write_text(json.dumps(schema, indent=2) + "\n")
PY

mkdir -p viewer/src/types
npx --yes json-schema-to-typescript@15.0.4 \
  --input schema/events.schema.json \
  --output viewer/src/types/events.ts \
  --unreachableDefinitions \
  --bannerComment "/* Generated by scripts/gen-schema.sh from schema/events.schema.json. Do not edit. */"
